using System.Globalization;
using Mapepire.EntityFrameworkCore.Metadata.Internal;

namespace Mapepire.EntityFrameworkCore.Migrations.Internal;

/// <summary>Generates Db2 for i DDL for EF Core migrations and <c>EnsureCreated</c>.</summary>
public class MapepireMigrationsSqlGenerator(MigrationsSqlGeneratorDependencies dependencies)
    : MigrationsSqlGenerator(dependencies)
{
    private ISqlGenerationHelper Sql => Dependencies.SqlGenerationHelper;

    /// <inheritdoc />
    protected override void ColumnDefinition(
        string? schema,
        string table,
        string name,
        ColumnOperation operation,
        IModel? model,
        MigrationCommandListBuilder builder)
    {
        if (operation.ComputedColumnSql is not null)
        {
            throw new NotSupportedException(
                $"Computed column '{table}.{name}' is not supported: Db2 for i has no general computed columns.");
        }

        var columnType = operation.ColumnType ?? GetColumnType(schema, table, name, operation, model)!;
        builder.Append(Sql.DelimitIdentifier(name)).Append(" ").Append(columnType);

        var identity = operation[MapepireAnnotationNames.Identity] is not null;

        // Db2 for i columns are nullable unless NOT NULL is specified; a bare NULL keyword is not accepted.
        if (!operation.IsNullable || identity)
        {
            builder.Append(" NOT NULL");
        }

        if (identity)
        {
            builder.Append(" GENERATED BY DEFAULT AS IDENTITY (START WITH 1, INCREMENT BY 1)");
        }
        else
        {
            DefaultValue(operation.DefaultValue, operation.DefaultValueSql, columnType, builder);
        }
    }

    /// <summary>
    /// Db2 for i DEFAULT clauses take a constant or special register, not a parenthesized expression or CAST,
    /// so date/time defaults are written as plain string constants.
    /// </summary>
    protected override void DefaultValue(
        object? defaultValue,
        string? defaultValueSql,
        string? columnType,
        MigrationCommandListBuilder builder)
    {
        if (defaultValueSql is not null)
        {
            builder.Append(" DEFAULT ").Append(defaultValueSql);
            return;
        }

        var literal = defaultValue switch
        {
            null => null,
            DateTime dt => columnType?.StartsWith("DATE", StringComparison.OrdinalIgnoreCase) == true
                ? Quote(dt.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture))
                : Quote(dt.ToString("yyyy-MM-dd-HH.mm.ss.ffffff", CultureInfo.InvariantCulture)),
            DateOnly d => Quote(d.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture)),
            TimeOnly t => Quote(t.ToString("HH.mm.ss", CultureInfo.InvariantCulture)),
            TimeSpan ts => Quote(ts.ToString(@"hh\.mm\.ss", CultureInfo.InvariantCulture)),
            _ => null,
        };

        if (literal is not null)
        {
            builder.Append(" DEFAULT ").Append(literal);
            return;
        }

        base.DefaultValue(defaultValue, defaultValueSql, columnType, builder);
    }

    /// <inheritdoc />
    protected override void Generate(AlterColumnOperation operation, IModel? model, MigrationCommandListBuilder builder)
    {
        var table = Sql.DelimitIdentifier(operation.Table, operation.Schema);
        var column = Sql.DelimitIdentifier(operation.Name);
        var old = operation.OldColumn;

        if (operation.ComputedColumnSql is not null)
        {
            throw new NotSupportedException(
                $"Computed column '{operation.Table}.{operation.Name}' is not supported: Db2 for i has no general computed columns.");
        }

        var identity = operation[MapepireAnnotationNames.Identity] is not null;
        var oldIdentity = old[MapepireAnnotationNames.Identity] is not null;
        if (identity != oldIdentity)
        {
            throw new NotSupportedException(
                $"Adding or removing the identity attribute of '{operation.Table}.{operation.Name}' is not supported by the Mapepire provider. "
                + "Recreate the table, or write the migration SQL by hand.");
        }

        var columnType = operation.ColumnType ?? GetColumnType(operation.Schema, operation.Table, operation.Name, operation, model)!;
        var oldType = old.ColumnType ?? GetColumnType(operation.Schema, operation.Table, operation.Name, old, model);

        if (!string.Equals(columnType, oldType, StringComparison.OrdinalIgnoreCase))
        {
            builder.Append("ALTER TABLE ").Append(table)
                .Append(" ALTER COLUMN ").Append(column)
                .Append(" SET DATA TYPE ").Append(columnType)
                .AppendLine(Sql.StatementTerminator);
            EndStatement(builder);
        }

        if (operation.IsNullable != old.IsNullable && !identity)
        {
            builder.Append("ALTER TABLE ").Append(table)
                .Append(" ALTER COLUMN ").Append(column)
                .Append(operation.IsNullable ? " DROP NOT NULL" : " SET NOT NULL")
                .AppendLine(Sql.StatementTerminator);
            EndStatement(builder);
        }

        if (!identity
            && (!Equals(operation.DefaultValue, old.DefaultValue)
                || !string.Equals(operation.DefaultValueSql, old.DefaultValueSql, StringComparison.Ordinal)))
        {
            builder.Append("ALTER TABLE ").Append(table).Append(" ALTER COLUMN ").Append(column);
            if (operation.DefaultValue is null && operation.DefaultValueSql is null)
            {
                builder.Append(" DROP DEFAULT");
            }
            else
            {
                builder.Append(" SET");
                DefaultValue(operation.DefaultValue, operation.DefaultValueSql, columnType, builder);
            }

            builder.AppendLine(Sql.StatementTerminator);
            EndStatement(builder);
        }
    }

    /// <inheritdoc />
    protected override void Generate(RenameColumnOperation operation, IModel? model, MigrationCommandListBuilder builder)
    {
        builder.Append("ALTER TABLE ").Append(Sql.DelimitIdentifier(operation.Table, operation.Schema))
            .Append(" RENAME COLUMN ").Append(Sql.DelimitIdentifier(operation.Name))
            .Append(" TO ").Append(Sql.DelimitIdentifier(operation.NewName))
            .AppendLine(Sql.StatementTerminator);
        EndStatement(builder);
    }

    /// <inheritdoc />
    protected override void Generate(RenameTableOperation operation, IModel? model, MigrationCommandListBuilder builder)
    {
        if (operation.NewSchema != operation.Schema && operation.NewSchema is not null)
        {
            throw new NotSupportedException("Moving a table to another schema is not supported by Db2 for i RENAME TABLE.");
        }

        if (operation.NewName is not null && operation.NewName != operation.Name)
        {
            builder.Append("RENAME TABLE ").Append(Sql.DelimitIdentifier(operation.Name, operation.Schema))
                .Append(" TO ").Append(Sql.DelimitIdentifier(operation.NewName))
                .AppendLine(Sql.StatementTerminator);
            EndStatement(builder);
        }
    }

    /// <inheritdoc />
    protected override void Generate(RenameIndexOperation operation, IModel? model, MigrationCommandListBuilder builder)
    {
        builder.Append("RENAME INDEX ").Append(Sql.DelimitIdentifier(operation.Name, operation.Schema))
            .Append(" TO ").Append(Sql.DelimitIdentifier(operation.NewName))
            .AppendLine(Sql.StatementTerminator);
        EndStatement(builder);
    }

    /// <summary>Indexes are schema objects in Db2 for i; create them in the table's schema.</summary>
    protected override void Generate(
        CreateIndexOperation operation,
        IModel? model,
        MigrationCommandListBuilder builder,
        bool terminate = true)
    {
        builder.Append("CREATE ");
        if (operation.IsUnique)
        {
            // Unique indexes over nullable columns allow repeated NULLs, matching EF Core's expectations.
            builder.Append(string.IsNullOrEmpty(operation.Filter) && HasNullableColumn(operation, model)
                ? "UNIQUE WHERE NOT NULL "
                : "UNIQUE ");
        }

        builder.Append("INDEX ")
            .Append(Sql.DelimitIdentifier(operation.Name, operation.Schema))
            .Append(" ON ")
            .Append(Sql.DelimitIdentifier(operation.Table, operation.Schema))
            .Append(" (");
        GenerateIndexColumnList(operation, model, builder);
        builder.Append(")");
        IndexOptions(operation, model, builder);

        if (terminate)
        {
            builder.AppendLine(Sql.StatementTerminator);
            EndStatement(builder);
        }
    }

    /// <inheritdoc />
    protected override void Generate(
        DropIndexOperation operation,
        IModel? model,
        MigrationCommandListBuilder builder,
        bool terminate = true)
    {
        builder.Append("DROP INDEX ").Append(Sql.DelimitIdentifier(operation.Name, operation.Schema));
        if (terminate)
        {
            builder.AppendLine(Sql.StatementTerminator);
            EndStatement(builder);
        }
    }

    /// <summary>Creates the schema unless it already exists (SQLSTATE 42710).</summary>
    protected override void Generate(EnsureSchemaOperation operation, IModel? model, MigrationCommandListBuilder builder)
    {
        var createSchema = "CREATE SCHEMA " + Sql.DelimitIdentifier(operation.Name);
        builder
            .AppendLine("BEGIN")
            .AppendLine("  DECLARE CONTINUE HANDLER FOR SQLSTATE '42710' BEGIN END;")
            .Append("  EXECUTE IMMEDIATE ").Append(Literal(createSchema)).AppendLine(";")
            .AppendLine("END");
        EndStatement(builder, suppressTransaction: true);
    }

    /// <inheritdoc />
    protected override void Generate(DropSchemaOperation operation, IModel? model, MigrationCommandListBuilder builder)
    {
        builder.Append("DROP SCHEMA ").Append(Sql.DelimitIdentifier(operation.Name)).AppendLine(Sql.StatementTerminator);
        EndStatement(builder, suppressTransaction: true);
    }

    /// <inheritdoc />
    protected override void Generate(RenameSequenceOperation operation, IModel? model, MigrationCommandListBuilder builder)
        => throw new NotSupportedException("Db2 for i does not support renaming sequences. Drop and recreate the sequence instead.");

    private static string Quote(string s) => "'" + s + "'";

    private static bool HasNullableColumn(CreateIndexOperation operation, IModel? model)
    {
        var table = model?.GetRelationalModel().FindTable(operation.Table, operation.Schema);
        return table is not null && operation.Columns.Any(c => table.FindColumn(c)?.IsNullable == true);
    }

    private static string Literal(string s) => "'" + s.Replace("'", "''") + "'";
}
